pub fn is_stopword(word: &str) -> bool {
    STOPWORDS.binary_search(&word).is_ok()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_list_is_sorted_and_free_of_repeats_so_binary_search_is_sound() {
        assert!(STOPWORDS.windows(2).all(|pair| pair[0] < pair[1]));
    }

    #[test]
    fn function_words_are_stopwords_and_content_words_are_not() {
        assert!(is_stopword("which"));
        assert!(is_stopword("there"));
        assert!(!is_stopword("lanterns"));
    }
}
